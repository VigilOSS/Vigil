"""`code/coverage/by-path` breaks the coverage obligation down by directory.

Every per-directory count is the same projection the summary and readiness
already make — the analysis-status buckets, analyzed-by-classification, the
unreviewed structural debt and accounted skips — grouped by path. A second
definition of any of them would let a directory table disagree with the gate
it is meant to explain, so these tests pin the rows to the summary and the
readiness debt count rather than to hand-picked numbers alone.
"""
from __future__ import annotations

import sqlite3

from app.services import code_analysis

from test_code_analysis_api import (
    _classify_file,
    _create_repo,
    _network_input_coverage,
    _owned,
    _publish_structural_callables,
    _refresh_repo_files,
    _source_hash,
    db_module,
    write_engagement,
)

_ANALYSIS_PATHS = (
    "src/auth/login.py",
    "src/auth/session.py",
    "src/auth/legacy.py",
    "src/billing/invoice.py",
    "src/billing/api/charge.py",
    "tools/gen.py",
    "main.py",
)


def _manifest(paths) -> list[dict[str, object]]:
    return [
        {
            "file_path": path,
            "language": "python",
            "loc": 10 + index,
            "file_hash": _source_hash(path),
            "header_snippet": "",
            "git_churn_score": 0,
            "has_past_cve_fix": False,
        }
        for index, path in enumerate(paths)
    ]


def _seed(client, isolate_settings, engagement_key: str):
    write_engagement(isolate_settings["engagements_dir"], engagement_key)
    base = f"/engagements/{engagement_key}/assessment/code"
    repo = _create_repo(client, engagement_key, repo_key=f"{engagement_key}-app")
    repo_id = int(repo["id"])
    files = _refresh_repo_files(client, engagement_key, repo_id, _manifest(_ANALYSIS_PATHS))
    _publish_structural_callables(client, engagement_key, repo_id, files, {})
    ids = {str(row["file_path"]): int(row["id"]) for row in files}
    tiers = {
        "src/auth/login.py": ("critical", 90),
        "src/auth/session.py": ("high", 70),
        "src/auth/legacy.py": ("medium", 40),
        "src/billing/invoice.py": ("high", 60),
        "src/billing/api/charge.py": ("critical", 80),
        "tools/gen.py": ("low", 10),
    }
    for path, (tier, priority) in tiers.items():
        _classify_file(client, engagement_key, ids[path], tier, priority)

    def queue(*paths: str) -> None:
        response = client.post(
            f"{base}/analysis-queue",
            json={
                "items": [
                    {"file_id": ids[path], "priority": tiers[path][1]} for path in paths
                ]
            },
        )
        assert response.status_code == 201, response.text

    def claim(path: str) -> dict[str, object]:
        response = client.post(
            f"{base}/analysis-queue/fetch",
            json={"limit": 1, "agent_name": "hunter", "path_prefix": [path]},
        )
        assert response.status_code == 200, response.text
        return response.json()[0]

    # Analyzed: a current receipt and a clean closeout.
    queue("src/auth/login.py")
    login = claim("src/auth/login.py")
    recorded = client.post(
        f"{base}/analysis-results",
        json=_owned(login, queue_item_id=login["id"], disposition="clean", evidence="read"),
    )
    assert recorded.status_code == 201, recorded.text
    done = client.post(
        f"{base}/analysis-queue/done",
        json=_owned(
            login,
            item_ids=[login["id"]],
            disposition="clean",
            notes="review complete",
            cwe_coverage=_network_input_coverage(default_effort=80),
        ),
    )
    assert done.status_code == 200, done.text

    queue("src/auth/session.py", "src/billing/invoice.py", "tools/gen.py")
    claim("src/billing/invoice.py")  # in progress
    generator = claim("tools/gen.py")
    skipped = client.post(
        f"{base}/analysis-queue/done",
        json=_owned(
            generator,
            item_ids=[generator["id"]],
            disposition="skipped",
            skip_reason="generated-code",
            notes="generated by the build",
        ),
    )
    assert skipped.status_code == 200, skipped.text

    # Structural quality states the indexer would publish. The reviewed file
    # is degraded too, so debt is shown to exclude a reviewed file.
    with sqlite3.connect(str(db_module.database_path())) as connection:
        connection.execute(
            "UPDATE code_files SET structural_analysis_status = 'degraded' WHERE id IN (?, ?)",
            (ids["src/auth/login.py"], ids["src/auth/legacy.py"]),
        )
        connection.execute(
            "UPDATE code_files SET structural_artifact_truncated = 1 WHERE id = ?",
            (ids["src/auth/legacy.py"],),
        )
        connection.execute(
            "UPDATE code_files SET structural_analysis_status = 'unsupported' WHERE id = ?",
            (ids["src/billing/api/charge.py"],),
        )
        connection.commit()

    reference = _create_repo(
        client, engagement_key, repo_key=f"{engagement_key}-framework", repo_role="reference"
    )
    reference_files = _refresh_repo_files(
        client,
        engagement_key,
        int(reference["id"]),
        _manifest(("src/auth/framework.py", "src/core/kernel.py")),
    )
    _publish_structural_callables(
        client, engagement_key, int(reference["id"]), reference_files, {}
    )
    with sqlite3.connect(str(db_module.database_path())) as connection:
        connection.execute(
            "UPDATE code_files SET structural_analysis_status = 'unsupported' WHERE repo_id = ?",
            (int(reference["id"]),),
        )
        connection.commit()
    return base, repo_id, int(reference["id"]), files


def test_directory_rows_carry_the_summary_projections(client, isolate_settings):
    base, repo_id, _reference_id, files = _seed(
        client, isolate_settings, "2026-11-05-coverage-by-path"
    )
    loc = {str(row["file_path"]): int(row["loc"]) for row in files}

    response = client.get(f"{base}/coverage/by-path")
    assert response.status_code == 200, response.text
    payload = response.json()
    assert payload["depth"] == 2
    assert payload["total"] == 4
    assert payload["has_more"] is False
    rows = payload["directories"]
    # Most uncovered critical+high first, then path.
    assert [row["path"] for row in rows] == ["src/billing", "src/auth", ".", "tools"]
    assert {row["repo_id"] for row in rows} == {repo_id}

    billing, auth, root, tools = rows
    assert billing["files"] == 2
    assert billing["loc"] == loc["src/billing/invoice.py"] + loc["src/billing/api/charge.py"]
    assert billing["by_classification"] == {
        "critical": {"count": 1, "analyzed": 0},
        "high": {"count": 1, "analyzed": 0},
    }
    assert billing["uncovered_critical_high"] == 2
    assert billing["by_status"] == {
        "analyzed": 0, "queued": 0, "in_progress": 1,
        "needs_context": 0, "classified": 1, "pending": 0,
    }
    assert billing["structural_debt"] == {
        "count": 1, "degraded": 0, "unsupported": 1, "truncated": 0,
    }

    assert auth["files"] == 3
    assert auth["by_classification"] == {
        "critical": {"count": 1, "analyzed": 1},
        "high": {"count": 1, "analyzed": 0},
        "medium": {"count": 1, "analyzed": 0},
    }
    assert auth["uncovered_critical_high"] == 1
    assert auth["by_status"]["analyzed"] == 1
    assert auth["by_status"]["queued"] == 1
    assert auth["by_status"]["classified"] == 1
    assert auth["structural_debt"] == {
        "count": 1, "degraded": 1, "unsupported": 0, "truncated": 1,
    }
    assert auth["accounted_skips"] == 0

    assert root["by_status"]["pending"] == 1
    assert root["by_classification"] == {"unclassified": {"count": 1, "analyzed": 0}}
    assert tools["accounted_skips"] == 1
    assert tools["by_status"]["classified"] == 1

    deeper = client.get(f"{base}/coverage/by-path?depth=3").json()["directories"]
    assert "src/billing/api" in {row["path"] for row in deeper}


def test_directory_rows_sum_to_the_coverage_summary(client, isolate_settings):
    base, _repo_id, _reference_id, _files = _seed(
        client, isolate_settings, "2026-11-05-coverage-by-path-sum"
    )
    summary = client.get(f"{base}/coverage").json()
    rows = client.get(f"{base}/coverage/by-path?depth=1").json()["directories"]

    assert sum(row["files"] for row in rows) == summary["total_files"] == len(_ANALYSIS_PATHS)
    assert sum(row["loc"] for row in rows) >= summary["confidence"]["overall_loc_analyzed"]
    by_status: dict[str, int] = {}
    by_classification: dict[str, dict[str, int]] = {}
    for row in rows:
        for status, count in row["by_status"].items():
            by_status[status] = by_status.get(status, 0) + count
        for tier, counts in row["by_classification"].items():
            bucket = by_classification.setdefault(tier, {"count": 0, "analyzed": 0})
            bucket["count"] += counts["count"]
            bucket["analyzed"] += counts["analyzed"]
    assert {key: value for key, value in by_status.items() if value} == summary["by_status"]
    assert by_classification == summary["by_classification"]


def test_directory_debt_matches_readiness_structural_debt(client, isolate_settings):
    base, _repo_id, _reference_id, _files = _seed(
        client, isolate_settings, "2026-11-05-coverage-by-path-debt"
    )
    readiness = client.get(f"{base}/readiness?target_phase=verify-variant").json()
    rows = client.get(f"{base}/coverage/by-path?depth=4").json()["directories"]

    assert readiness["structural_debt_count"] == 2
    assert sum(row["structural_debt"]["count"] for row in rows) == readiness[
        "structural_debt_count"
    ]


def test_reference_repositories_owe_no_directory_rows(client, isolate_settings):
    base, repo_id, reference_id, _files = _seed(
        client, isolate_settings, "2026-11-05-coverage-by-path-reference"
    )

    rows = client.get(f"{base}/coverage/by-path").json()["directories"]
    assert {row["repo_id"] for row in rows} == {repo_id}
    assert sum(row["files"] for row in rows if row["path"] == "src/auth") == 3
    scoped = client.get(f"{base}/coverage/by-path?repo_id={reference_id}").json()
    assert scoped["total"] == 0
    assert scoped["directories"] == []


def test_path_prefix_and_paging_scope_the_directory_rows(client, isolate_settings):
    base, _repo_id, _reference_id, _files = _seed(
        client, isolate_settings, "2026-11-05-coverage-by-path-scope"
    )

    scoped = client.get(f"{base}/coverage/by-path?path_prefix=src/billing").json()
    assert [row["path"] for row in scoped["directories"]] == ["src/billing"]
    assert client.get(f"{base}/coverage/by-path?path_prefix=src/bill").json()["total"] == 0
    assert client.get(f"{base}/coverage/by-path?path_prefix=/src").status_code == 400

    first = client.get(f"{base}/coverage/by-path?limit=1").json()
    assert first["total"] == 4
    assert first["count"] == 1
    assert first["has_more"] is True
    assert [row["path"] for row in first["directories"]] == ["src/billing"]
    second = client.get(f"{base}/coverage/by-path?limit=1&offset=1").json()
    assert [row["path"] for row in second["directories"]] == ["src/auth"]
    assert client.get(f"{base}/coverage/by-path?depth=0").status_code == 422


def test_directory_rows_break_terminal_work_down_by_disposition(client, isolate_settings):
    """"Done, by whom, with what verdict" is half of what a wave plan needs.

    The row already says how much is analyzed; without a disposition split it
    cannot say whether that review found anything, so a directory full of
    findings reads the same as a directory of clean closes. The split reads the
    same latest current queue attempt `by_status` and `accounted_skips` read, so
    it cannot disagree with them.
    """
    base, _repo_id, _reference_id, _files = _seed(
        client, isolate_settings, "2026-11-06-coverage-by-path-disposition"
    )

    rows = client.get(f"{base}/coverage/by-path").json()["directories"]
    by_path = {row["path"]: row for row in rows}

    assert by_path["src/auth"]["by_disposition"] == {"clean": 1}
    assert by_path["tools"]["by_disposition"] == {"skipped": 1}
    # An in-progress claim has no verdict yet, and neither has a pending file.
    assert by_path["src/billing"]["by_disposition"] == {}
    assert by_path["."]["by_disposition"] == {}

    # Every counted disposition is one the vocabulary admits — a reopened row
    # carries `superseded`, which is not a verdict and must not be counted —
    # and across these rows the verdicts account for exactly the analyzed and
    # accounted-skip files the same row reports.
    for row in rows:
        assert set(row["by_disposition"]) <= code_analysis._VALID_DISPOSITIONS
        analyzed = sum(
            tier["analyzed"] for tier in row["by_classification"].values()
        )
        assert sum(row["by_disposition"].values()) == analyzed + row["accounted_skips"]
