import { formatDateTime } from "../lib/format";

interface Props {
  generatedAt: string;
  vigilVersion: string;
  mode: "draft" | "final";
}

export function Footer({ generatedAt, vigilVersion, mode }: Props) {
  return (
    <footer className="rpt-footer">
      <p className="rpt-footer-disclaimer">
        Generated by Vigil — for authorized security assessment use only.
        {mode === "draft" &&
          " This is a DRAFT report; findings may not yet be fully verified or reviewed."}
      </p>
      <div className="rpt-footer-meta">
        <span>Vigil {vigilVersion}</span>
        <span>Mode: {mode}</span>
        <span>Generated {formatDateTime(generatedAt)}</span>
      </div>
    </footer>
  );
}

export default Footer;
